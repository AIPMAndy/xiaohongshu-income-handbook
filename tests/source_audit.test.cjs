#!/usr/bin/env node
'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const root=path.resolve(__dirname,'..');
const ctx={window:{}};
vm.runInNewContext(fs.readFileSync(path.join(root,'assets/data.js'),'utf8'),ctx,{timeout:3000});
const {normalizeSources,filteredSources,exportText}=require('../assets/source-audit.js');
const all=normalizeSources(ctx.window.HANDBOOK.sources);
assert.equal(all.length,18,'source record regression');
assert.equal(new Set(all.map(x=>x.url)).size,16,'deduplicated URL regression');
assert(all.every(x=>x.url.startsWith('https://')));
assert.equal(filteredSources(all,{q:'专业号',category:'all',status:'all'},{}).length,2);
assert(filteredSources(all,{q:'电子资源',category:'merchant',status:'all'},{}).some(x=>x.id==='digital_qual'));
assert(!filteredSources(all,{q:'电子资源',category:'law',status:'all'},{}).length);
const one=all.find(x=>x.id==='professional_compliance');
assert.equal(filteredSources(all,{q:'',category:'all',status:'reviewed'},{[one.id]:'2026-11-21'}).length,1);
assert.equal(filteredSources(all,{q:'',category:'all',status:'pending'},{[one.id]:'2026-11-21'}).length,17);
const txt=exportText([one],{[one.id]:'2026-11-21'},'2026-11-21T00:00:00Z');
assert(txt.startsWith('\ufeff'));
assert(txt.includes(one.url)&&txt.includes('已自行复核｜2026-11-21'));
assert(txt.includes('历史资料核对截点：2026-11-02'));
assert(txt.includes('AIPMAndy')&&txt.includes('https://www.a6no1.cn/'));
const html=fs.readFileSync(path.join(root,'source-audit.html'),'utf8');
assert(html.includes('rel="canonical"')&&html.includes('source-audit.js'));
const matches=[...html.matchAll(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/g)];
assert.equal(matches.length,1);const schema=JSON.parse(matches[0][1]);
assert.equal(schema['@type'],'WebPage');assert.equal(schema.citation.length,3);
assert(schema.citation.every(x=>x.url.startsWith('https://')));
console.log('OK: 18 source records / 16 URLs, filters, local-review semantics, TXT export, JSON-LD');
